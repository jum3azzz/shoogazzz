// ============================================================
// QUESTION CATEGORIES
// ============================================================

export const questionCategories = {

    gender: {
        label: "GENDER",
        property: "gender"
    },

    eyeColor: {
        label: "EYES",
        property: "eyeColor"
    },

    hair: {
        label: "HAIR",
        property: "hair"
    },

    hairColor: {
        label: "HAIR COLOR",
        property: "hairColor"
    },

    skinTone: {
        label: "SKIN",
        property: "skinTone"
    },

    accessories: {
        label: "ACCESSORIES",
        property: "accessories"
    },

    facialHair: {
        label: "FACIAL HAIR",
        property: "facialHair"
    }

};


// ============================================================
// GET CHARACTER
// ============================================================

export function getCharacterById(id) {

    return characters.find(
        character =>
            Number(character.id) === Number(id)
    );

}


// ============================================================
// GET CHARACTER BY NAME
// ============================================================

export function getCharacterByName(name) {

    return characters.find(
        character =>
            character.name.toLowerCase() ===
            String(name).toLowerCase()
    );

}


// ============================================================
// GET CATEGORY VALUES
// ============================================================

export function getCategoryValues(category) {

    const config =
        questionCategories[category];

    if (!config) {
        return [];
    }

    const values =
        characters.map(
            character =>
                character[config.property]
        );

    return [
        ...new Set(values)
    ];

}


// ============================================================
// GET CHARACTERS BY CATEGORY
// ============================================================

export function getCharactersByCategory(
    category,
    value
) {

    const config =
        questionCategories[category];

    if (!config) {
        return [];
    }

    return characters.filter(
        character =>
            character[config.property] === value
    );

}


// ============================================================
// CHECK CHARACTER ATTRIBUTE
// ============================================================

export function characterMatches(
    characterId,
    category,
    value
) {

    const character =
        getCharacterById(
            characterId
        );

    const config =
        questionCategories[category];

    if (!character || !config) {
        return false;
    }

    return (
        character[config.property] === value
    );

}


// ============================================================
// RANDOM CHARACTER
// ============================================================

export function getRandomCharacter() {

    const index =
        Math.floor(
            Math.random() *
            characters.length
        );

    return characters[index];

}


// ============================================================
// RANDOM CHARACTER ID
// ============================================================

export function getRandomCharacterId() {

    return getRandomCharacter().id;

}


// ============================================================
// CHARACTER COUNT
// ============================================================

export function getCharacterCount() {

    return characters.length;

}


// ============================================================
// ALL CHARACTER NAMES
// ============================================================

export function getCharacterNames() {

    return characters.map(
        character =>
            character.name
    );

}


